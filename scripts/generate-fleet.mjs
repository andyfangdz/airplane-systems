#!/usr/bin/env node
/** One authored fleet registration; explicit generated imports retain per-aircraft route splitting. */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { createServer } from "vite";
import { format, resolveConfig } from "prettier";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const registry = JSON.parse(await readFile(resolve(root, "aircraft/fleet.json"), "utf8"));
const fleet = registry.aircraft;
const ids = fleet.map((entry) => entry.id);
if (
  !ids.length ||
  ids.some((id) => typeof id !== "string" || !/^[a-z][a-z0-9]*$/.test(id)) ||
  new Set(ids).size !== ids.length ||
  !ids.includes(registry.default) ||
  fleet.some(
    (entry) => typeof entry.walk !== "boolean" || (entry.preload !== undefined && typeof entry.preload !== "boolean"),
  )
)
  throw new Error("Invalid aircraft/fleet.json registration");

const header = "// Generated by scripts/generate-fleet.mjs from aircraft/fleet.json; run npm run fleet:generate.\n";
for (const entry of await readdir(resolve(root, "app/(fleet)"), { withFileTypes: true })) {
  if (!entry.isDirectory() || ids.includes(entry.name)) continue;
  const obsolete = resolve(root, `app/(fleet)/${entry.name}/[[...sys]]/page.tsx`);
  const exists = await readFile(obsolete, "utf8").catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return undefined;
  });
  if (exists !== undefined) throw new Error(`Remove unregistered aircraft route: ${obsolete}`);
}
const outputs = new Map();
outputs.set(
  "lib/aircraft-ids.ts",
  `${header}
export const AIRCRAFT_IDS = ${JSON.stringify(ids)} as const;
export type AircraftId = (typeof AIRCRAFT_IDS)[number];
export const DEFAULT_AIRCRAFT: AircraftId = ${JSON.stringify(registry.default)};
`,
);
outputs.set(
  "aircraft/metas.ts",
  `${header}
/** Lightweight metadata only. Never imports an aircraft runtime or its scene. */
import type { AircraftMeta } from "./types";
${ids.map((id) => `import { ${id.toUpperCase()}_META } from "./${id}/meta";`).join("\n")}
export const FLEET_META: AircraftMeta[] = [${ids.map((id) => `${id.toUpperCase()}_META`).join(", ")}];
export const viewPathsOf = (meta: AircraftMeta) => [\`/\${meta.id}\`, ...meta.systems.map((s) => \`/\${meta.id}/\${s.id}\`)];
export const VIEW_PATHS = ["/", ...FLEET_META.flatMap(viewPathsOf)];
`,
);
outputs.set(
  "aircraft/index.ts",
  `${header}
/** Whole-fleet entry for tests and authoring only. Browser routes import their own definition directly. */
import { registerAircraft } from "@/lib/fleet";
${ids.map((id) => `import { ${id.toUpperCase()} } from "./${id}";`).join("\n")}
export const FLEET = [${ids.map((id) => id.toUpperCase()).join(", ")}];
registerAircraft(...FLEET);
export * from "@/lib/fleet";
`,
);
for (const { id, preload } of fleet) {
  const symbol = id.toUpperCase();
  if (preload) {
    await readFile(resolve(root, `app/(fleet)/${id}/[[...sys]]/prepare.tsx`)).catch((error) => {
      throw new Error(`Preloaded aircraft ${id} requires its route's prepare.tsx`, { cause: error });
    });
  }
  outputs.set(
    `app/(fleet)/${id}/[[...sys]]/page.tsx`,
    `${header}
import { ${symbol} } from "@/aircraft/${id}";
import { ${symbol}_META } from "@/aircraft/${id}/meta";
import App from "@/components/App";
import { airplaneMetadata, routeSys, systemParams, type AirplaneProps } from "../../airplane-route";
${preload ? 'import { Prepare } from "./prepare";' : ""}
export const dynamicParams = false;
export const generateStaticParams = systemParams(${symbol}_META);
export const metadata = airplaneMetadata(${symbol}_META);
export default async function Page(props: AirplaneProps) {
  return (${preload ? "<><Prepare />" : ""}<App def={${symbol}} sys={await routeSys(${symbol}_META, props)} />${preload ? "</>" : ""});
}
`,
  );
}

const server = await createServer({
  configFile: false,
  root,
  resolve: { alias: { "@": root } },
  server: { middlewareMode: true, watch: null },
  optimizeDeps: { noDiscovery: true },
});
try {
  // Evaluate only light metadata, never full definitions or procedural geometry.
  const entries = [];
  const views = [];
  for (const { id } of fleet) {
    const meta = (await server.ssrLoadModule(`/aircraft/${id}/meta.ts`))[`${id.toUpperCase()}_META`];
    if (meta.id !== id) throw new Error(`Metadata identity mismatch for ${id}`);
    entries.push({ id, name: meta.name, sub: meta.sub });
    views.push({ id, systems: meta.systems.map((system) => system.id) });
  }
  outputs.set("aircraft/views.json", JSON.stringify(views));
  outputs.set(
    "lib/fleet-index.ts",
    `${header}
import type { AircraftId } from "./systems";
/** Picker labels compiled from aircraft metadata without loading system descriptions or scenes. */
export const FLEET_INDEX: { id: AircraftId; name: string; sub: string }[] = ${JSON.stringify(entries)};
`,
  );
  const { ENGINE_IDS } = await server.ssrLoadModule("/engines/index.ts");
  const { COMPONENT_IDS } = await server.ssrLoadModule("/engines/components/index.ts");
  const template = await readFile(resolve(root, "infra/cloudfront/view-rewrite.template.js"), "utf8");
  if (template.split("/* @ROUTE_IDS@ */").length !== 2) throw new Error("Expected one route registry placeholder");
  const routeIds = [
    `var AIRCRAFT_IDS = ${JSON.stringify(ids)};`,
    `var ENGINE_IDS = ${JSON.stringify(ENGINE_IDS)};`,
    `var COMPONENT_IDS = ${JSON.stringify(COMPONENT_IDS)};`,
  ].join("\n");
  const edge = await format(header + template.replace("/* @ROUTE_IDS@ */", routeIds), {
    ...(await resolveConfig(resolve(root, "infra/cloudfront/view-rewrite.js"))),
    parser: "babel",
  });
  outputs.set("infra/cloudfront/view-rewrite.js", edge);
  const site = JSON.parse(await readFile(resolve(root, "infra/aws/site.json"), "utf8"));
  const functions = Object.values(site.Resources).filter((resource) => resource.Type === "AWS::CloudFront::Function");
  if (functions.length !== 1) throw new Error("Expected one CloudFront viewer function");
  functions[0].Properties.FunctionCode = edge;
  outputs.set("infra/aws/site.json", JSON.stringify(site));
} finally {
  await server.close();
}

const stale = [];
for (const [path, source] of outputs) {
  const filepath = resolve(root, path);
  const text = await format(source, { ...(await resolveConfig(filepath)), filepath });
  const old = await readFile(filepath, "utf8").catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return "";
  });
  if (old === text) continue;
  if (check) stale.push(path);
  else {
    await mkdir(dirname(filepath), { recursive: true });
    await writeFile(filepath, text);
  }
}
if (stale.length) throw new Error(`Stale generated registrations: ${stale.join(", ")}. Run npm run fleet:generate.`);
console.log(`Fleet registration ${check ? "verified" : "generated"}: ${ids.length} aircraft, ${outputs.size} outputs`);
